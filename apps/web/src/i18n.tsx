type Ctx = { lang: Lang; t: (k: string, vars?: Record<string, string | number>) => string; setLang: (l: Lang) => void };

const I18n = createContext<Ctx>({ lang: "fa", t: (k) => k, setLang: () => {} });

function readLang(): Lang {
  const raw = localStorage.getItem("expert.lang");
  return LANGS.some((x) => x.id === raw) ? (raw as Lang) : "fa";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang);
  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem("expert.lang", l);
  };
  useEffect(() => {
    const meta = LANGS.find((x) => x.id === lang) || LANGS[0];
    document.documentElement.lang = lang;
    document.documentElement.dir = meta.dir;
  }, [lang]);
  const t = useMemo(
    () => (k: string, vars?: Record<string, string | number>) => {
      let s = dict[lang][k] || dict.fa[k] || k;
      if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b));
      return s;
    },
    [lang]
  );
  return <I18n.Provider value={{ lang, t, setLang }}>{children}</I18n.Provider>;
}

export function useI18n() {
  return useContext(I18n);
}

export function LanguageMenu() {
  const { lang, setLang, t } = useI18n();
  const [open, setOpen] = useState(false);
  const cur = LANGS.find((x) => x.id === lang)!;
  return (
    <div className="lang-wrap">
      <button type="button" className="btn ghost lang-btn" aria-haspopup="listbox" aria-expanded={open} onClick={() => setOpen((v) => !v)}>
        <span aria-hidden>{cur.flag}</span> {t("language")}
      </button>
      {open && (
        <ul className="lang-menu" role="listbox">
          {LANGS.map((l) => (
            <li key={l.id}>
              <button type="button" className={l.id === lang ? "active" : ""} onClick={() => { setLang(l.id); setOpen(false); }}>
                <span aria-hidden>{l.flag}</span> {l.name}
              </button>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}
